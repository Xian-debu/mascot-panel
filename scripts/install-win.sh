#!/usr/bin/env bash
# 把 dist/mascot 安装到 %LOCALAPPDATA%\mascot\app\<version>，原子切换 current.txt，生成回滚脚本。
#
#   WIN_ROOT=/mnt/c/Users/Public/mascot bash scripts/install-win.sh [--autostart]
#
# 设计沿用 docs/11 的 win-admin 两包模型：
#   版本目录不可变（安装时整体复制），current.txt 是唯一指针，
#   “升级”= 新增一个版本目录 + 改一行指针；“回滚”= 改回上一行。
set -euo pipefail

WIN_ROOT=${WIN_ROOT:-/mnt/c/Users/Public/mascot}
VERSION=${VERSION:-0.1.0}
PY="$WIN_ROOT/venv/Scripts/python.exe"
SRC="$WIN_ROOT/dist/mascot"

if [ ! -x "$PY" ]; then
  echo "missing $PY" >&2
  exit 3
fi
if [ ! -d "$SRC" ]; then
  echo "missing $SRC（先跑 scripts/build-win.sh）" >&2
  exit 3
fi

# 用户目录从 Windows 环境取，避免把用户名写死进仓库
# 用 sys.stdout.write 输出，避免 Windows 的 CRLF 把 \r 带进目录名（曾装到 "Local\r"）
LOCAL_WIN="$("$PY" -c 'import os,sys;sys.stdout.write(os.environ["LOCALAPPDATA"])')"
LOCAL="$(wslpath -u "$LOCAL_WIN")/mascot"
DEST="$LOCAL/app/$VERSION"

echo "== 安装 $VERSION -> $LOCAL_WIN\\mascot\\app\\$VERSION"
mkdir -p "$LOCAL/app"
# 覆盖安装前先停掉旧实例：Windows 会锁住正在使用的 dll，直接 rm 会报 Input/output error
if [ -x "$DEST/mascot.exe" ]; then
  "$DEST/mascot.exe" ctl stop >/dev/null 2>&1 || true
  sleep 1
fi
rm -rf "$DEST"
cp -r "$SRC" "$DEST"

printf '%s\n' "$VERSION" >"$LOCAL/current.txt.tmp"
mv -f "$LOCAL/current.txt.tmp" "$LOCAL/current.txt"

cat >"$LOCAL/rollback.bat" <<EOF
@echo off
chcp 65001 >nul
rem Generated by mascot scripts/install-win.sh: stop new version, offer old one.
setlocal
set "MASCOT=%LOCALAPPDATA%\\mascot"
if exist "%MASCOT%\\app\\$VERSION\\mascot.exe" (
  "%MASCOT%\\app\\$VERSION\\mascot.exe" ctl stop >nul 2>&1
)
"%MASCOT%\\app\\$VERSION\\mascot.exe" autostart off >nul 2>&1
echo 新版已停止、自启已关闭。
if exist "E:\\TX-Pet\\scripts\\start_frameless.bat" (
  echo 启动旧版: E:\\TX-Pet\\scripts\\start_frameless.bat
  call "E:\\TX-Pet\\scripts\\start_frameless.bat"
) else (
  echo 未找到旧版启动脚本，请手动启动 E:\\TX-Pet。
)
endlocal
EOF

# cmd.exe 的批处理必须是 CRLF（LF-only 会在 if(...) 块里解析错位）；
# 同时把 heredoc 留下的双反斜杠收成单反斜杠。
sed -i -e 's/\\\\/\\/g' -e 's/$/\r/' "$LOCAL/rollback.bat"

if [ "${1:-}" = "--autostart" ]; then
  echo "== 开启开机自启"
  "$DEST/mascot.exe" autostart on --exe "$LOCAL_WIN\\mascot\\app\\$VERSION\\mascot.exe"
fi

echo "== done: $LOCAL_WIN\\mascot\\app\\$VERSION\\mascot.exe"
echo "   current.txt = $(cat "$LOCAL/current.txt")"
echo "   回滚脚本: $LOCAL_WIN\\mascot\\rollback.bat"
